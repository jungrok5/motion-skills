// node <skill>/scripts/styles.mjs list [--group print]        the hands, grouped, with what each suits
// node <skill>/scripts/styles.mjs show <id>                     one hand's full recipe and its settings
// node <skill>/scripts/styles.mjs pick <id> [--studio dir] [--set key=value …] [--note "…"]
//                                                               save it as the studio's house style (house-style.json):
//                                                               every piece in the studio then draws in this hand
// node <skill>/scripts/styles.mjs house [--studio dir]           print the current house style
// node <skill>/scripts/styles.mjs doc                            regenerate references/STYLES.md from the modules
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { SKILL, args, findHouse } from './_lib.mjs'

const a = args(process.argv.slice(2))
const [cmd = 'list', id] = a._
const { GROUPS, STYLE_IDS } = await import(pathToFileURL(join(SKILL, 'lib/styles/index.js')).href)
const load = async (sid) => (await import(pathToFileURL(join(SKILL, 'lib/styles', `${sid}.js`)).href)).default
const all = async () => { const out = []; for (const sid of STYLE_IDS) { try { out.push(await load(sid)) } catch { /* not written */ } } return out }
const die = (m) => { console.error('styles: ' + m); process.exit(1) }

if (cmd === 'list') {
  const have = new Map((await all()).map((s) => [s.id, s]))
  for (const g of GROUPS) {
    if (a.group && a.group !== g.key) continue
    console.log(`\n${g.ko} (${g.key})`)
    for (const sid of g.ids) { const s = have.get(sid); console.log(s ? `  ${sid.padEnd(16)} ${s.ko} · ${s.name} — ${s.bestFor}` : `  ${sid.padEnd(16)} (not written)`) }
  }
  console.log(`\n${have.size} hands. Show one: styles.mjs show <id> · compare them on your own piece: sheet.mjs <piece> --all`)
} else if (cmd === 'show') {
  if (!id) die('show <id>')
  const s = await load(id).catch(() => die(`no style "${id}"`))
  console.log(`${s.ko} · ${s.name} (${s.id})\n`)
  for (const k of ['medium', 'mark', 'edge', 'paper', 'palette', 'bestFor', 'source']) if (s[k]) console.log(`${k.padEnd(8)} ${s[k]}`)
  console.log(`order    ${(s.order || []).join(' → ')}`)
  console.log(`settings ${JSON.stringify(s.defaults || {})}  (override in house-style.json → tweaks.${s.id}, or --set on pick)`)
} else if (cmd === 'pick') {
  if (!id) die('pick <id>')
  if (!STYLE_IDS.includes(id)) die(`no style "${id}". One of: ${STYLE_IDS.join(', ')}`)
  const s = await load(id)
  const studio = resolve(a.studio || '.'), f = join(studio, 'house-style.json')
  const house = existsSync(f) ? JSON.parse(readFileSync(f, 'utf8')) : { tweaks: {} }
  house.style = id
  house.tweaks ||= {}
  const sets = [].concat(a.set || []).filter((x) => x !== true)
  if (sets.length) {
    house.tweaks[id] ||= {}
    for (const kv of sets) {
      const [k, ...rest] = String(kv).split('='), v = rest.join('=')
      if (!(k in (s.defaults || {}))) console.warn(`note: "${k}" is not one of ${s.id}'s settings (${Object.keys(s.defaults || {}).join(', ') || 'none'})`)
      try { house.tweaks[id][k] = JSON.parse(v) } catch { house.tweaks[id][k] = v }
    }
  }
  if (a.note) house.note = String(a.note)
  house.source = `anidoodle style recipe (${s.source || s.id}) — https://github.com/alexgreensh/anidoodle`
  writeFileSync(f, JSON.stringify(house, null, 2) + '\n')
  console.log(`house style → ${s.ko} · ${s.name} (${id})  ${f}`)
  if (house.tweaks[id]) console.log('settings', JSON.stringify(house.tweaks[id]))
} else if (cmd === 'house') {
  const f = a.studio ? join(resolve(a.studio), 'house-style.json') : findHouse('.')
  if (!f || !existsSync(f)) die('no house-style.json here or above; pick one: styles.mjs pick <id>')
  console.log(f + '\n' + readFileSync(f, 'utf8'))
} else if (cmd === 'doc') {
  const have = new Map((await all()).map((s) => [s.id, s]))
  let md = `# The hands\n\nGenerated by \`node scripts/styles.mjs doc\` from \`lib/styles/*.js\`. Do not edit by hand.\n` +
    `Each hand was studied from a style recipe in anidoodle (https://github.com/alexgreensh/anidoodle, Apache-2.0) and re-implemented for this skill's scene model.\n`
  for (const g of GROUPS) {
    md += `\n## ${g.ko} (\`${g.key}\`)\n\n| id | hand | suits | medium · mark | order | settings |\n|---|---|---|---|---|---|\n`
    for (const sid of g.ids) {
      const s = have.get(sid)
      if (!s) { md += `| \`${sid}\` | (not written) | | | | |\n`; continue }
      const cell = (x) => String(x || '').replace(/\|/g, '/').replace(/\n/g, ' ')
      md += `| \`${sid}\` | ${s.ko} · ${s.name} | ${cell(s.bestFor)} | ${cell(s.medium)} — ${cell(s.mark)} | ${cell((s.order || []).join(' → '))} | ${cell(Object.keys(s.defaults || {}).map((k) => '`' + k + '`').join(' '))} |\n`
    }
  }
  writeFileSync(join(SKILL, 'references/STYLES.md'), md)
  console.log(`references/STYLES.md: ${have.size} hands`)
} else die(`unknown command "${cmd}" (list · show · pick · house · doc)`)
