#!/usr/bin/env python3
"""Build references/STYLE-INDEX.md: one searchable list of every look canvas-film can draw on.

Sources: this skill's own references/STYLES.md (21 looks, proven here) and a clone of Lemo-Opuscar
(github.com/lemomo-ai/lemo-opuscar, MIT): its technique styles (styles/*/style.json → STYLE.md) and the
98 OPUSCAR film looks (styleboard/opuscar98_styles.json → prompt_en).
  git clone --depth 1 https://github.com/lemomo-ai/lemo-opuscar /tmp/lemo-opuscar
  python3 canvas-film/scripts/style-index.py /tmp/lemo-opuscar
"""
import glob, json, os, re, sys

if len(sys.argv) != 2:
    sys.exit(__doc__)
src = sys.argv[1]
here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
head = os.popen(f"git -C {src} rev-parse --short HEAD 2>/dev/null").read().strip() or "?"


def cell(s):
    return re.sub(r"\s+", " ", str(s)).replace("|", "/").strip()


def first_sentence(s, n=170):
    s = cell(s)
    m = re.match(r"(.+?[.!?])(\s|$)", s)
    s = m.group(1) if m else s
    return s if len(s) <= n else s[: n - 1].rstrip() + "…"


styles = [json.load(open(p, encoding="utf-8")) for p in glob.glob(f"{src}/styles/[!_]*/style.json")]
styles.sort(key=lambda s: (s.get("category_en", ""), s["slug"]))
films = json.load(open(f"{src}/styleboard/opuscar98_styles.json", encoding="utf-8"))["films"]

own = [l for l in open(f"{here}/references/STYLES.md", encoding="utf-8") if l.startswith("| ") and "---" not in l][1:]

out = [
    "# Style index — every look to choose from",
    "",
    "<!-- generated by scripts/style-index.py; do not edit by hand -->",
    f"{len(own)} proven canvas-film looks + {len(styles)} Lemo-Opuscar technique styles + {len(films)} OPUSCAR film looks.",
    f"Lemo-Opuscar © LemoLab, MIT (code/text) · demo films CC BY 4.0 — github.com/lemomo-ai/lemo-opuscar @ {head}.",
    "Borrow the craft, write your own renderer; never copy a demo's shots, characters or music.",
    "(\"Clawd\" in the OPUSCAR lines is the mascot walking through that film — ignore it; keep the technique.)",
    "",
    "## How to search (do this for every film, before proposing styles)",
    "1. Write the source's **meaning per beat** in a few words (e.g. \"a small thing spreads through the whole\", \"swept clean\", \"a sacrifice\").",
    "2. Scan **all three tables** below for looks whose *medium itself* acts that meaning out (ink that floods, a print pulled",
    "   again and again, a blueprint that develops) — not for surface mood. Note 6–10 candidates.",
    "3. Drop what breaks SCENE-RULES: looks marked **needs real material** (photos, scans, footage, data) can't be used as",
    "   is — everything here is drawn in code; 3D looks need WebGL and cost more; check the portrait (1080×1920) composition.",
    "4. Read the full brief of the 3–5 survivors: `styles/<slug>/STYLE.md` (+ `DEMO.md`) or the film's `prompt_en` +",
    "   `desc_en` in `styleboard/opuscar98_styles.json` of a Lemo-Opuscar clone (`git clone --depth 1 …`); for the",
    "   canvas-film looks, `references/STYLES.md` and the one-scroll-bible scenes.",
    "5. Propose: one recommendation with *why it carries the meaning*, 2–3 alternatives, each with its native move",
    "   (the one moment only that medium can do) placed on the story's turn.",
    "",
    f"## A. canvas-film looks ({len(own)}) — proven in this pipeline; details in STYLES.md",
    "Code: each look is one self-contained scene (style + Bible story together) in github.com/jungrok5/one-scroll-bible",
    "`motion/pilot/<scene>.html` (shared: `lib.js`, `goldline.js`). Read it for technique; packaged, reusable looks are in `kits/`.",
    "",
    "| scene | style | meaning carried | code |",
    "|---|---|---|---|",
]
for l in own:
    c = [x.strip() for x in l.strip().strip("|").split("|")]
    out.append(f"| {c[0]} | {c[1]} | {c[2]} | `motion/pilot/{c[0]}.html` |")

out += ["", f"## B. Lemo-Opuscar technique styles ({len(styles)}) — brief: `styles/<slug>/STYLE.md`", "",
        "| slug | style | category | its demo, in one line | good for |", "|---|---|---|---|---|"]
for s in styles:
    cat = s.get("category_en", "")
    flag = " · **needs real material**" if cat == "Evidence Films" else ""
    out.append(f"| `{s['slug']}` | {cell(s['en'])} | {cell(cat)}{flag} | {first_sentence(s.get('line', ''))} | "
               f"{cell(', '.join(s.get('uses', [])))} |")

out += ["", f"## C. OPUSCAR 98 film looks ({len(films)}) — brief: `prompt_en` of entry `no` in `styleboard/opuscar98_styles.json`", "",
        "| no | film (year) | look | render | technique, in one line |", "|---|---|---|---|---|"]
for f in films:
    out.append(f"| {f['no']} | {cell(f['title'])} ({cell(f['year'])}) | {cell(f['style_en'])} | {cell(f.get('render', ''))} | "
               f"{first_sentence(f.get('desc_en', ''))} |")

path = f"{here}/references/STYLE-INDEX.md"
open(path, "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"wrote {path}: {len(own)} + {len(styles)} + {len(films)} looks")
